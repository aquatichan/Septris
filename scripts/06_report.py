"""Step 6: write docs/results.md from the result files (no hand-typed numbers)."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

RES = ROOT / "outputs/results"
NAMES = {"random": "Random review (same budget)", "sirs": "SIRS ranking", "news": "NEWS-inspired score",
         "lr": "Logistic regression (current values)", "lgbm_values": "LightGBM, values only",
         "lgbm_missing": "LightGBM, measurement pattern only", "lgbm_combined": "**SignalBridge** (LightGBM, combined)",
         "lgbm_shortcuts": "LightGBM + shortcut fields (never deployed)"}
ORDER = ["random", "sirs", "news", "lr", "lgbm_values", "lgbm_missing", "lgbm_combined", "lgbm_shortcuts"]


def pct(v, lo=None, hi=None):
    if pd.isna(v):
        return "–"
    s = f"{100 * v:.1f}%"
    return s if lo is None else f"{s} ({100 * lo:.1f}–{100 * hi:.1f})"


def pp(r):
    return f"{100 * r.point:+.1f} ({100 * r.lo:+.1f} to {100 * r.hi:+.1f})"


def main():
    t = pd.read_csv(RES / "results_table.csv")
    d = pd.read_csv(RES / "paired_differences.csv")
    h = pd.read_csv(RES / "hourly_metrics.csv")
    u = pd.read_csv(RES / "utility_scores.csv")
    bnt = pd.read_csv(RES / "before_new_testing.csv")
    null = json.loads((RES / "null_check.json").read_text())
    fc = json.loads((RES / "failure_cases.json").read_text())
    sig = json.loads((RES / "testing_signal_training.json").read_text())
    audit = pd.read_csv(ROOT / "outputs/data_audit.csv").pivot(index="metric", columns="hospital", values="value")
    audit = audit.apply(lambda col: pd.to_numeric(col, errors="coerce").fillna(col))
    av = pd.read_csv(ROOT / "outputs/availability.csv")

    def diff(T, k, comp):
        r = d[(d.test == T) & (d.k == k) & (d.comparison == comp)]
        return r.iloc[0] if len(r) else None

    L = ["# Results", "",
         "> This project is a prototype and is not medical advice.", "",
         "Every number below is generated by `scripts/06_report.py` from `outputs/results/`. "
         "Rates are the mean of 5 admission orders; brackets are 95% intervals from 200 patient-level "
         "bootstrap replicates. Paired differences are computed inside each replicate.", ""]

    # headline
    L += ["## Headline", ""]
    for T in ("A", "B"):
        o = "B" if T == "A" else "A"
        g = t[(t.test == T) & (t.k == 3) & (t.subgroup == "all")].set_index("policy")
        home, ext, rnd = g.loc[f"{T}:lgbm_combined"], g.loc[f"{o}:lgbm_combined"], g.loc["random"]
        L.append(f"- **Hospital {T}:** with 3 reviews per 12-hour shift, SignalBridge flagged "
                 f"{home.caught6_n:.0f} of {home.eligible:.0f} eligible sepsis cases "
                 f"({pct(home.caught6, home.caught6_lo, home.caught6_hi)}) 6–12 hours before onset with its "
                 f"home model, and {pct(ext.caught6, ext.caught6_lo, ext.caught6_hi)} with the model trained at "
                 f"Hospital {o}. Random reviews under the same budget flagged {pct(rnd.caught6, rnd.caught6_lo, rnd.caught6_hi)}.")
    L.append("")

    # main table per test hospital
    for T in ("A", "B"):
        o = "B" if T == "A" else "A"
        L += [f"## Hospital {T} test patients, 3 reviews per shift", "",
              "| Policy | Trained at | Caught 6–12 h early | Missed | False reviews / shift | Late reviews / shift | Median lead (h) |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
        g = t[(t.test == T) & (t.k == 3) & (t.subgroup == "all")]
        for key in ORDER:
            pols = [key] if key in ("random", "sirs", "news") else [f"{T}:{key}", f"{o}:{key}"]
            for pol in pols:
                r = g[g.policy == pol]
                if r.empty:
                    continue
                r = r.iloc[0]
                where = "–" if ":" not in pol else (f"{pol[0]} (home)" if pol[0] == T else f"{pol[0]} (unseen)")
                L.append(f"| {NAMES[key]} | {where} | {r.caught6_n:.0f} of {r.eligible:.0f} · "
                         f"{pct(r.caught6, r.caught6_lo, r.caught6_hi)} | {r.missed_n:.0f} · {pct(r.missed)} | "
                         f"{r.false_per_shift:.2f} ({r.false_per_shift_lo:.2f}–{r.false_per_shift_hi:.2f}) | "
                         f"{r.late_per_shift:.2f} | {r.median_lead:.1f} |")
        L.append("")

    # paired differences
    L += ["## The claims the project stands on (paired differences, percentage points)", "",
          "| Test hospital | Comparison | Caught 6–12 h early, difference (95% CI) | Interval excludes 0? |",
          "| --- | --- | --- | --- |"]
    comps = ["lgbm_combined (home) minus random", "lgbm_combined: home minus external",
             "lgbm_combined (home) minus SIRS", "combined minus LR (home)",
             "reliance: combined minus values-only (home)", "missingness-only (home) minus random",
             "lgbm_values: home minus external", "lgbm_missing: home minus external",
             "shortcuts minus combined (home)", "SIRS minus random", "NEWS minus random"]
    labels = {"lgbm_combined (home) minus random": "SignalBridge (home) − random",
              "lgbm_combined: home minus external": "SignalBridge: home model − unseen-hospital model",
              "lgbm_combined (home) minus SIRS": "SignalBridge (home) − SIRS",
              "combined minus LR (home)": "SignalBridge (home) − logistic regression",
              "reliance: combined minus values-only (home)": "Reliance: combined − values-only",
              "missingness-only (home) minus random": "Sufficiency: measurement-pattern-only − random",
              "lgbm_values: home minus external": "Values-only: home − unseen",
              "lgbm_missing: home minus external": "Measurement-pattern-only: home − unseen",
              "shortcuts minus combined (home)": "Shortcut fields − portable model",
              "SIRS minus random": "SIRS − random", "NEWS minus random": "NEWS − random"}
    for T in ("A", "B"):
        for c in comps:
            r = diff(T, 3, c)
            if r is not None:
                L.append(f"| {T} | {labels[c]} | {pp(r)} | {'yes' if r.excludes_zero else 'no'} |")
    r = diff("A", 3, "false reviews/shift: combined (home) minus random")
    r2 = diff("B", 3, "false reviews/shift: combined (home) minus random")
    L += ["", f"False reviews per shift, SignalBridge (home) minus random: A {r.point:+.2f} "
              f"({r.lo:+.2f} to {r.hi:+.2f}); B {r2.point:+.2f} ({r2.lo:+.2f} to {r2.hi:+.2f}).", ""]

    # hourly
    L += ["## Hourly discrimination (test hours before onset, 12-hour target)", "",
          "| Model | A→A AUROC | B→A AUROC | B→B AUROC | A→B AUROC | A→A PR-AUC | B→B PR-AUC |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for key in ORDER[1:]:
        def g_(tr, te, col):
            r = h[(h.model == key) & (h.test == te) & ((h.train == tr) | (h.train == "-"))]
            return f"{r.iloc[0][col]:.3f}" if len(r) else "–"
        L.append(f"| {NAMES[key]} | {g_('A','A','auroc')} | {g_('B','A','auroc')} | {g_('B','B','auroc')} | "
                 f"{g_('A','B','auroc')} | {g_('A','A','pr_auc')} | {g_('B','B','pr_auc')} |")
    prev = h.groupby("test")["prevalence"].first()
    L += ["", f"Positive-hour prevalence: A {100 * prev['A']:.2f}%, B {100 * prev['B']:.2f}%.", ""]

    # utility
    L += ["## Official PhysioNet 2019 utility (Tier 1)", "",
          "Threshold chosen on the home hospital's validation patients; score computed on test patients with the official labels.", "",
          "| Model | A→A | B→A | B→B | A→B |", "| --- | --- | --- | --- | --- |"]
    for key in ORDER[1:]:
        def gu(tr, te):
            r = u[(u.model == key) & (u.train == tr) & (u.test == te)]
            return f"{r.iloc[0].test_utility:.3f}" if len(r) else "–"
        L.append(f"| {NAMES[key]} | {gu('A','A')} | {gu('B','A')} | {gu('B','B')} | {gu('A','B')} |")
    L.append("")

    # budgets
    L += ["## Other budgets (Tier 1): caught 6–12 h early", "",
          "| Test | Reviews / shift | Random | SIRS | SignalBridge (home) | SignalBridge (unseen) |",
          "| --- | --- | --- | --- | --- | --- |"]
    for T in ("A", "B"):
        o = "B" if T == "A" else "A"
        for k in (1, 2, 3, 5):
            g = t[(t.test == T) & (t.k == k) & (t.subgroup == "all")].set_index("policy")
            c = lambda p: pct(g.loc[p].caught6, g.loc[p].caught6_lo, g.loc[p].caught6_hi)
            L.append(f"| {T} | {k} | {c('random')} | {c('sirs')} | {c(f'{T}:lgbm_combined')} | {c(f'{o}:lgbm_combined')} |")
    L.append("")

    # subgroups
    L += ["## Subgroups (Tier 0), home model, 3 reviews per shift", "",
          "| Test | Group | Eligible | SignalBridge caught 6–12 h | Random |", "| --- | --- | --- | --- | --- |"]
    for T in ("A", "B"):
        for sub in ["age <50", "age 50-64", "age 65-79", "age 80+", "sex 0", "sex 1", "fully observed"]:
            g = t[(t.test == T) & (t.k == 3) & (t.subgroup == sub)].set_index("policy")
            s_, r_ = g.loc[f"{T}:lgbm_combined"], g.loc["random"]
            L.append(f"| {T} | {sub} | {s_.eligible:.0f} | {pct(s_.caught6, s_.caught6_lo, s_.caught6_hi)} | "
                     f"{pct(r_.caught6, r_.caught6_lo, r_.caught6_hi)} |")
    L += ["", "Sex is reported as coded in the dataset (0/1); the data dictionary does not say which code is which. "
              "Race is not in this dataset. Small groups give wide intervals. Age is capped (B: "
              f"{audit.loc['age_share_at_max_pct', 'B']}% of patients at the maximum of {audit.loc['age_max', 'B']}). "
              "Equal results on a few recorded groups do not prove fairness.", ""]

    # before new testing
    L += ["## Alerts before new lab results appeared (Tier 1)", "",
          f"Rule (frozen on {sig['training_eligible_patients']} training patients before test results were opened: "
          f"it fired for {sig['signal_found_pct']}% of them, a median {sig['median_hours_before_onset']:.0f} h before onset): {sig['rule']}.", "",
          "Admission order 1, 3 reviews per shift. Lab times are result times, not order times, so \"ahead\" is an upper bound.", "",
          "| Test | Policy | Caught early | Ahead of new lab results | After | No signal |", "| --- | --- | --- | --- | --- | --- |"]
    for _, r in bnt.iterrows():
        if r.policy in ("random", "sirs") or r.policy.endswith(("lgbm_combined", "lgbm_values", "lgbm_missing")):
            if ":" in r.policy and r.policy[0] != r.test:
                continue
            key = r.policy.split(":")[-1]
            L.append(f"| {r.test} | {NAMES[key].replace('**', '')} | {r.caught} | {r.ahead_of_new_testing} | "
                     f"{r.after_new_testing} | {r.no_signal_found} |")
    L.append("")

    # cohort + checks
    L += ["## Cohort and checks", "",
          f"- Eligible septic / uncertain onset / non-septic: A {audit.loc['group_eligible_septic','A']:.0f} / "
          f"{audit.loc['group_uncertain_onset','A']:.0f} / {audit.loc['group_non_septic','A']:.0f}; "
          f"B {audit.loc['group_eligible_septic','B']:.0f} / {audit.loc['group_uncertain_onset','B']:.0f} / "
          f"{audit.loc['group_non_septic','B']:.0f}. Uncertain-onset patients ({audit.loc['group_uncertain_onset','A']:.0f} + "
          f"{audit.loc['group_uncertain_onset','B']:.0f}) arrive already within 6 h of onset: no 6-hour warning is possible for them.",
          f"- Cross-hospital rule dropped: {', '.join(av.loc[av.flag_hospital_specific, 'variable'])}. Variables with very "
          "different coverage that the frozen rule kept: "
          + ", ".join(f"{r.variable} (A {r.A_patients_pct:.0f}% vs B {r.B_patients_pct:.0f}% of patients)"
                      for r in av.itertuples() if abs(r.A_patients_pct - r.B_patients_pct) > 50) + ".",
          f"- Null check: LightGBM trained on shuffled labels caught {pct(null['shuffled_caught6_mean'])}, inside random "
          f"review's interval {pct(null['random_caught6_interval'][0])}–{pct(null['random_caught6_interval'][1])}: "
          f"{'pass' if null['shuffled_inside_random_interval'] else 'FAIL'}.",
          f"- Leakage, split, label, slot, alert-class and utility tests: see `tests/` (`python -m pytest -q tests`).",
          f"- Too-good check: highest internal hourly AUROC of a portable model is "
          f"{h[(h.train == h.test) & (h.model != 'lgbm_shortcuts')].auroc.max():.3f} (alarm threshold 0.95).", ""]

    # failure cases
    L += ["## Failure cases (picked by the frozen rule, A→A, admission order 1)", "",
          f"- **Missed:** {fc['missed']['patient_id']}, onset at record hour {fc['missed']['t_onset']:.0f}, "
          f"{fc['missed']['hours_in_window']} hours inside its 12-hour window, never reviewed early.",
          f"- **False alert:** {fc['false_alert']['patient_id']}, a {fc['false_alert']['n_hours']}-hour stay with "
          f"{fc['false_alert']['false_reviews']} false reviews and no recorded onset.",
          "", "Open both in the app (Review round → jump buttons)."]
    (ROOT / "docs/results.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:20]))


if __name__ == "__main__":
    main()
